#!/usr/bin/env node
// Читает отчёт scrape-teikin-report.json + парсит каждый PDF через pdftotext.
// На выходе: src/data/teikin-catalog-auto.ts — авто-сгенерированный каталог
// с минимально необходимыми полями (image, teikin_pistons, bore, cc, cyl, fuel, oem).
//
// Запуск (после scrape-teikin.mjs):
//   node scripts/gen-teikin-catalog.mjs

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SITE_ROOT = resolve(__dirname, '..');
const PDF_CACHE = resolve(__dirname, 'cache-teikin-pdfs');
const REPORT = resolve(__dirname, 'scrape-teikin-report.json');
const OUT_TS = resolve(SITE_ROOT, 'src/data/teikin-catalog-auto.ts');

const toSlug = (s) =>
  s.toLowerCase().replace(/[\/\\]/g, '-').replace(/[^a-z0-9а-я\-]+/gi, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');

// ---------- PDF parser ----------
// Возвращает поля, которые получилось распознать. Парсер делает best-effort.
function parsePdf(pdfPath) {
  // -layout сохраняет колонки PDF — данные мотора стоят на одной строке.
  const txt = execFileSync('pdftotext', ['-layout', pdfPath, '-'], { encoding: 'utf8' });
  const lines = txt.split('\n');

  const out = {};

  // FUEL — в первых ~5 строках есть DIESEL / GASOLINE
  const head = lines.slice(0, 6).join(' ');
  if (/\bDIESEL\b/i.test(head)) out.fuel = 'DIESEL';
  else if (/\bGAS(OLINE)?\b/i.test(head)) out.fuel = 'GASOLINE';

  // cc / cyl
  const ccM = txt.match(/(\d{3,5})\s*cc/i);
  if (ccM) out.cc = parseInt(ccM[1], 10);
  const cylM = txt.match(/(\d{1,2})\s*cyl\.?/i);
  if (cylM) out.cyl = parseInt(cylM[1], 10);

  // BORE — строка с "cc Ø ... XX.XX" — bore идёт сразу после "cc Ø"
  const boreLineM = txt.match(/cc\s*Ø\s+(\d{2,3}\.\d{2})/);
  if (boreLineM) {
    const v = parseFloat(boreLineM[1]);
    if (v >= 40 && v <= 160) out.bore_mm = v;
  }

  // PIN diameter — Ø NN.NNN (3 decimals — пин обычно с 3 знаками точности)
  const pinM = txt.match(/Ø\s+(\d{2}\.\d{3})/);
  if (pinM) {
    const v = parseFloat(pinM[1]);
    if (v >= 15 && v <= 60) out.pin_diameter_mm = v;
  }

  // OEM piston — берём первую колонку REFERENCE NO.
  // С -layout колонки видны по позиции. Ищем строку "REFERENCE NO." и читаем следующие строки,
  // вырезая по тому же столбцу.
  const refLineIdx = lines.findIndex((l) => /REFERENCE NO\.?/i.test(l));
  if (refLineIdx >= 0) {
    // Позиция первой "REFERENCE NO." — это колонка OEM поршня
    const col = lines[refLineIdx].indexOf('REFERENCE');
    const oems = [];
    for (let i = refLineIdx + 1; i < Math.min(refLineIdx + 10, lines.length); i++) {
      const l = lines[i];
      if (!l.trim()) continue;
      // Берём подстроку начиная с позиции колонки, до 30 символов
      const chunk = l.substring(col, col + 30).trim();
      if (!chunk) continue;
      // Стоп если попали в следующую секцию
      if (/^(TEIKIN NO|Surface Treatment|Bore Clearance|RINGS|PIN|BUSHING|FLANGED|MRC|MP)/i.test(chunk)) break;
      // Берём только первый «токен» из чанка (пробелами разделены колонки)
      const first = chunk.split(/\s{2,}/)[0].trim();
      if (/^[A-Z0-9][A-Z0-9\-\/]{4,}[A-Z0-9]$/.test(first) || /^\d{4,}-\d+/.test(first)) {
        oems.push(first);
      }
    }
    if (oems.length) out.oem_piston = oems;
  }

  return out;
}

// ---------- main ----------
const report = JSON.parse(readFileSync(REPORT, 'utf8'));
const entries = [];

for (const m of report.matched) {
  const slug = toSlug(m.engine_code);
  const pdfPath = resolve(PDF_CACHE, `${slug}.pdf`);
  const e = {
    engine_code: m.engine_code,
    brand_name: m.brand_name,
    display_name: `${m.brand_name} ${m.teikin_model}`,
    image: `/teikin-catalog/${slug}.png`,
    teikin_pistons: m.articles,
  };
  if (existsSync(pdfPath)) {
    try {
      Object.assign(e, parsePdf(pdfPath));
    } catch (err) {
      console.warn(`[parse-fail] ${m.engine_code}: ${err.message}`);
    }
  }
  entries.push(e);
}

// Sanity: для 1KZ сверим что bore=96.00 — иначе парсер сломан
const oneKz = entries.find((e) => e.engine_code === '1KZ');
if (oneKz) {
  console.log(`[sanity] 1KZ: bore=${oneKz.bore_mm} cc=${oneKz.cc} cyl=${oneKz.cyl} fuel=${oneKz.fuel} oem=${(oneKz.oem_piston || []).join(',')}`);
}

// ---------- write TS ----------
const lines = [
  '// AUTO-GENERATED by scripts/gen-teikin-catalog.mjs. Do not edit by hand.',
  '// Источник: teikin.com e-catalog + pdftotext.',
  '// Ручные записи в teikin-catalog.ts ПЕРЕЗАПИСЫВАЮТ авто-данные.',
  '',
  "import type { TeikinEntry } from './teikin-catalog';",
  '',
  'export const teikinAutoCatalog: Record<string, Partial<TeikinEntry>> = {',
];

for (const e of entries) {
  const obj = {
    display_name: e.display_name,
    image: e.image,
    teikin_pistons: e.teikin_pistons,
  };
  if (e.fuel) obj.fuel = e.fuel;
  if (e.cc) obj.cc = e.cc;
  if (e.cyl) obj.cyl = e.cyl;
  if (e.bore_mm != null) obj.bore_mm = e.bore_mm;
  if (e.pin_diameter_mm != null) obj.pin_diameter_mm = e.pin_diameter_mm;
  if (e.oem_piston?.length) obj.oem_piston = e.oem_piston;

  const json = JSON.stringify(obj, null, 2).replace(/^/gm, '    ').replace(/^    /, '  ');
  lines.push(`  ${JSON.stringify(e.engine_code)}: ${json},`);
}

lines.push('};');
lines.push('');

writeFileSync(OUT_TS, lines.join('\n'));
console.log(`Wrote ${entries.length} entries -> ${OUT_TS}`);
